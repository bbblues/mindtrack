<script>
function noteTemplatesPage(initialTemplates) {
    return {
        templates: initialTemplates,
        modalOpen: false,
        editingId: null,
        name: '',
        content: '',
        formError: null,
        pageError: null,
        saving: false,
        csrf: <?= json_encode(csrf_hash()) ?>,

        openCreate() {
            this.editingId = null;
            this.name = '';
            this.content = '';
            this.formError = null;
            this.modalOpen = true;
        },
        openEdit(template) {
            this.editingId = template.id;
            this.name = template.name;
            this.content = template.content;
            this.formError = null;
            this.modalOpen = true;
        },
        closeModal() {
            this.modalOpen = false;
            this.editingId = null;
            this.name = '';
            this.content = '';
            this.formError = null;
        },
        async submit() {
            this.formError = null;
            this.saving = true;

            const url = this.editingId
                ? <?= json_encode(site_url('settings/note-templates/update/')) ?> + this.editingId
                : <?= json_encode(site_url('settings/note-templates')) ?>;

            const params = new URLSearchParams();
            params.set('name', this.name);
            params.set('content', this.content);

            try {
                const res = await fetch(url, {
                    method: 'POST',
                    headers: {
                        'X-CSRF-TOKEN': this.csrf,
                        'X-Requested-With': 'XMLHttpRequest',
                        'Content-Type': 'application/x-www-form-urlencoded',
                    },
                    body: params.toString(),
                });

                const data = await res.json();

                if (data.csrf_token) {
                    this.csrf = data.csrf_token;
                }

                if (!data.success) {
                    this.formError = data.errors && Object.keys(data.errors).length
                        ? Object.values(data.errors).join(' ')
                        : (data.message || 'Não foi possível salvar o modelo de nota.');
                    this.saving = false;
                    return;
                }

                if (data.template) {
                    if (this.editingId) {
                        const index = this.templates.findIndex((t) => t.id === this.editingId);
                        if (index !== -1) this.templates[index] = data.template;
                    } else {
                        this.templates.push(data.template);
                        this.templates.sort((a, b) => a.name.localeCompare(b.name));
                    }
                }

                this.closeModal();
            } catch (e) {
                this.formError = 'Falha na comunicação com o servidor.';
            }

            this.saving = false;
        },
        async remove(template) {
            if (!window.confirm(`Excluir o modelo "${template.name}"?`)) {
                return;
            }

            this.pageError = null;

            try {
                const res = await fetch(<?= json_encode(site_url('settings/note-templates/delete/')) ?> + template.id, {
                    method: 'POST',
                    headers: {
                        'X-CSRF-TOKEN': this.csrf,
                        'X-Requested-With': 'XMLHttpRequest',
                        'Content-Type': 'application/x-www-form-urlencoded',
                    },
                    body: new URLSearchParams(),
                });

                const data = await res.json();

                if (data.csrf_token) {
                    this.csrf = data.csrf_token;
                }

                if (!data.success) {
                    this.pageError = data.message || 'Não foi possível excluir o modelo de nota.';
                    return;
                }

                this.templates = this.templates.filter((t) => t.id !== template.id);
            } catch (e) {
                this.pageError = 'Falha na comunicação com o servidor.';
            }
        }
    };
}
</script>

